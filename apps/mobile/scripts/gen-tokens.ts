/**
 * Generates src/theme/tokens.ts from apps/web/src/styles/tokens.css, the single source of truth.
 * Run: pnpm --filter mobile tokens
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cssPath = join(here, '../../web/src/styles/tokens.css');
const outPath = join(here, '../src/theme/tokens.ts');

const css = readFileSync(cssPath, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

function block(selector: RegExp): string {
  const m = selector.exec(css);
  if (!m) throw new Error(`tokens.css: block not found for ${selector}`);
  const start = m.index + m[0].length;
  return css.slice(start, css.indexOf('}', start));
}

function declarations(body: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const m of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) out.set(m[1]!, m[2]!.replace(/\s+/g, ' ').trim());
  return out;
}

const lightRaw = declarations(block(/^:root\s*\{/m));
// The dark values are repeated in the data-theme block and the media query; both are identical.
const darkOverrides = declarations(block(/^:root\[data-theme='dark'\],\s*\[data-surface='night'\]\s*\{/m));
const darkRaw = new Map([...lightRaw, ...darkOverrides]);

export const names = [...new Set([...lightRaw.keys(), ...darkOverrides.keys()])];

function resolve(raw: Map<string, string>, value: string, depth = 0): string {
  if (depth > 8) return value;
  const next = value.replace(/var\(--([\w-]+)\)/g, (whole, name: string) => raw.get(name) ?? whole);
  return next === value ? value : resolve(raw, next, depth + 1);
}

type Shadow = {
  shadowColor: string;
  shadowOffset: { width: number; height: number };
  shadowOpacity: number;
  shadowRadius: number;
  elevation: number;
};
type Value = string | number | Shadow | null;

const COLOR = /^(#[0-9a-f]{3,8}|rgba?\([\d.,\s]+\))$/i;

function parseShadow(value: string): Shadow | undefined {
  // React Native takes one shadow: use the first layer of a stack.
  const first = value.split(/,(?![^(]*\))/)[0]!.trim();
  const m = /^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+(rgba?\([\d.,\s]+\))$/.exec(first);
  if (!m) return undefined;
  const [, x, y, blur, color] = m;
  const alpha = /rgba\([^)]*,\s*([\d.]+)\)/.exec(color!)?.[1];
  return {
    shadowColor: color!.replace(/rgba\(([^)]*),\s*[\d.]+\)/, 'rgb($1)'),
    shadowOffset: { width: Number(x), height: Number(y) },
    shadowOpacity: alpha === undefined ? 1 : Number(alpha),
    shadowRadius: Number(blur) / 2,
    elevation: Math.round(Number(blur) / 4),
  };
}

/** undefined means the value has no React Native equivalent and is skipped. */
function convert(name: string, value: string): Value | undefined {
  if (value === 'none') return null;
  if (name.startsWith('shadow-')) return parseShadow(value);
  if (COLOR.test(value)) return value;
  let m = /^(-?[\d.]+)px$/.exec(value);
  if (m) return Number(m[1]);
  m = /^(-?[\d.]+)rem$/.exec(value);
  if (m) return Number(m[1]) * 16;
  m = /^(-?[\d.]+)ms$/.exec(value);
  if (m) return Number(m[1]);
  m = /^(-?[\d.]+)s$/.exec(value);
  if (m) return Number(m[1]) * 1000;
  if (/^-?[\d.]+$/.test(value)) return Number(value);
  if (/^[\d.]+%$/.test(value)) return value;
  return undefined;
}

const camel = (name: string) => name.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

function build(raw: Map<string, string>): { values: Record<string, Value>; skipped: string[] } {
  const values: Record<string, Value> = {};
  const skipped: string[] = [];
  for (const name of names) {
    const v = convert(name, resolve(raw, raw.get(name)!));
    if (v === undefined) skipped.push(name);
    else values[camel(name)] = v;
  }
  return { values, skipped };
}

const light = build(lightRaw);
const dark = build(darkRaw);

const header = `/**
 * GENERATED by scripts/gen-tokens.ts from apps/web/src/styles/tokens.css. Do not edit by hand:
 * change tokens.css and run \`pnpm --filter mobile tokens\`.
 *
 * Units: px as numbers, rem as numbers at 1rem = 16, ms/s durations as milliseconds, \`none\` as null,
 * shadows as React Native shadow props (first layer of a stack), var() references resolved per scheme.
 * Skipped from the value objects (names stay in tokenNames): font stacks, clamp()/calc() values, em
 * letter-spacing, gradients, url() images, cubic-bezier easings, inset/ring box-shadows (focus-ring,
 * result-time-hover), and color-scheme.
 * Skipped here: ${light.skipped.join(', ')}
 */
`;

const render = (v: Value): string => {
  if (v === null) return 'null';
  if (typeof v === 'object') {
    return `{ shadowColor: '${v.shadowColor}', shadowOffset: { width: ${v.shadowOffset.width}, height: ${v.shadowOffset.height} }, shadowOpacity: ${v.shadowOpacity}, shadowRadius: ${v.shadowRadius}, elevation: ${v.elevation} }`;
  }
  return typeof v === 'string' ? `'${v}'` : String(v);
};
const renderObj = (o: Record<string, Value>) =>
  Object.entries(o)
    .map(([k, v]) => `  ${k}: ${render(v)},`)
    .join('\n');

const out = `${header}
export interface Shadow {
  shadowColor: string;
  shadowOffset: { width: number; height: number };
  shadowOpacity: number;
  shadowRadius: number;
  elevation: number;
}

export const light = {
${renderObj(light.values)}
};

export const dark: typeof light = {
${renderObj(dark.values)}
};

/** Every custom property declared in tokens.css, kebab-case without the leading dashes. */
export const tokenNames: string[] = [
${names.map((n) => `  '${n}',`).join('\n')}
];
`;

writeFileSync(outPath, out);
console.log(`tokens.ts: ${Object.keys(light.values).length} values, ${light.skipped.length} skipped`);
